def build(name,pages):
    story=[]; md=[]
    for index,(title,sections) in enumerate(pages):
        if index: story.append(PageBreak())
        story.append(Paragraph(escape(title),styles['title'])); md.append('# '+title+'\n')
        for heading,body in sections:
            story.extend([Paragraph(escape(heading),styles['head']),Paragraph(escape(body),styles['body'])])
            md.extend(['## '+heading+'\n',body+'\n'])
    SimpleDocTemplate(str(OUT/(name+'.pdf')),pagesize=(595.28,841.89),rightMargin=48,leftMargin=48,topMargin=48,bottomMargin=62,title=pages[0][0],author='K-ODAME').build(story,onFirstPage=footer,onLaterPages=footer)
    (OUT/(name+'.md')).write_text('\n'.join(md),encoding='utf-8')

