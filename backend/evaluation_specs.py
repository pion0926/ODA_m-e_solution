def flatten_evidence(groups: list[dict]) -> list[dict]:
    return [{"category": group["category"], "name": item} for group in groups for item in group["items"]]


def build_criteria() -> list[dict]:
    criteria = []
    for base in BASE_CRITERIA:
        criterion = {
            **deepcopy(base),
            "currentScore4": 1,
            "targetScore4": 4,
            "scoreStatus": "문서 미업로드",
            "scoreScale": {"min": 1, "max": 4, "unit": "점"},
        }
        spec = EVALUATION_SPECS.get(criterion["id"])
        if spec:
            criterion.update(
                {
                    "evidence": flatten_evidence(spec["evidenceGroups"]),
                    "evidenceGroups": deepcopy(spec["evidenceGroups"]),
                    "commonScoringNotes": deepcopy(spec["commonScoringNotes"]),
                    "scoringRubric": deepcopy(spec["scoringRubric"]),
                    "evaluationPrompt": spec["evaluationPrompt"],
                    "evaluationResult": {
                        "status": "waiting",
                        "score": None,
                        "summary": spec["waitingSummary"],
                        "sections": [],
                        "model": "google/gemini-3.1-flash-lite",
                        "updatedAt": None,
                    },
                }
            )
        else:
            criterion["evidence"] = [{"category": "기본 증빙", "name": name} for name in base.get("evidence", [])]
        criteria.append(criterion)
    return criteria


def get_evaluation_prompt(criterion_id: str) -> str | None:
    spec = EVALUATION_SPECS.get(criterion_id)
    return spec["evaluationPrompt"] if spec else None


