def grade(total: float) -> tuple[str, str]:
    if total >= 18:
        return "A", "매우 성공적"
    if total >= 16:
        return "B", "성공적"
    if total >= 14:
        return "C", "성공적"
    if total >= 12:
        return "D", "부분 성공적"
    if total >= 10:
        return "E", "부분 성공적"
    return "F", "미흡"
